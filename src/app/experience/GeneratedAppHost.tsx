import { useState } from 'react'
import { Blocks } from 'lucide-react'
import { AppRuntimePanel, type RuntimeView } from '@/app/runtime/components/AppRuntimePanel'
import { useOs } from '@/app/os/use-os'
import { getGeneratedApp } from '@/app/registry/applicationRegistry'
import type { AppProps } from '@/app/registry/types'
import { useApplications } from '@/app/registry/use-applications'
import { MockBadge } from '@/components/os/MockBadge'
import { Button } from '@/components/ui/button'
import { Empty, EmptyDescription, EmptyHeader, EmptyMedia, EmptyTitle } from '@/components/ui/empty'
import { scenarioForDomain } from '@/data/studio-scenarios.mock'
import { ExperienceRenderer } from './ExperienceRenderer'

/**
 * Window content for every application published from Application Studio.
 * Renders the pinned blueprint version; republishing remounts it on the new version.
 */
export function GeneratedAppHost({ windowId }: AppProps) {
  useApplications() // re-render when the registry changes (republish)
  const { openApp } = useOs()
  const record = getGeneratedApp(windowId)
  const [mode, setMode] = useState<'workspace' | 'runtime'>('workspace')
  const [runtimeView, setRuntimeView] = useState<RuntimeView>({ kind: 'list' })

  if (!record) {
    return (
      <Empty className="h-full">
        <EmptyHeader>
          <EmptyMedia variant="icon">
            <Blocks />
          </EmptyMedia>
          <EmptyTitle>This application is no longer registered</EmptyTitle>
          <EmptyDescription>It may have been removed when browser storage was cleared.</EmptyDescription>
        </EmptyHeader>
        <Button size="sm" variant="outline" onClick={() => openApp('application-studio')}>
          Open Application Studio
        </Button>
      </Empty>
    )
  }

  return (
    <div className="flex h-full min-h-0 flex-col">
      <div className="flex shrink-0 flex-wrap items-center gap-2 border-b bg-chrome px-4 py-1.5 text-xs text-muted-foreground">
        <span>
          Generated by Application Studio · blueprint <span className="tabular-nums">{record.version}</span>
        </span>
        <div role="group" aria-label="Application view" className="ml-auto flex gap-0.5">
          <Button size="xs" variant={mode === 'workspace' ? 'secondary' : 'ghost'} aria-pressed={mode === 'workspace'} onClick={() => setMode('workspace')}>
            Workspace
          </Button>
          <Button size="xs" variant={mode === 'runtime' ? 'secondary' : 'ghost'} aria-pressed={mode === 'runtime'} onClick={() => setMode('runtime')}>
            Transactions
          </Button>
        </div>
        <MockBadge />
        <Button size="xs" variant="ghost" onClick={() => openApp('system-explorer', { section: 'applications', app: record.id })}>
          Details
        </Button>
        <Button size="xs" variant="ghost" onClick={() => openApp('application-studio', { project: record.projectId })}>
          Edit in Studio
        </Button>
      </div>
      <div className="min-h-0 flex-1">
        {mode === 'runtime' ? (
          <AppRuntimePanel appId={record.id} view={runtimeView} onView={setRuntimeView} />
        ) : (
        <ExperienceRenderer key={record.version} blueprint={record.blueprint} initialRecords={scenarioForDomain(record.domain).sampleRecords} persistKey={record.id} />
        )}
      </div>
    </div>
  )
}
